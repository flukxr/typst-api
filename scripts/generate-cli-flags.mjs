// Derives the CLI flag inventory from the exact per-release `--help`
// snapshots: for every subcommand and every flag, the exact releases that
// have it, whether it takes a value, and the values it accepts per release.
//
// The output, `src/capabilities/cli-flags.generated.ts`, is committed. The
// option tables in `src/commands/shared.ts` map the package's options to these
// flags and take every version boundary from here, so no boundary is typed by
// hand.
//
// Usage:
//   node scripts/generate-cli-flags.mjs            regenerate
//   node scripts/generate-cli-flags.mjs --check    fail when out of date
//   ... [--snapshot-root DIR]
// Without a snapshot corpus `--check` is skipped with a notice, so offline
// checkouts still build.
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";

import { parseHelpFlags } from "./cli-help.mjs";
import { repositorySnapshotRoot } from "./snapshot-root.mjs";
import { compareExactVersions as compareVersions } from "./release-inventory.mjs";

const ROOT = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const OUTPUT = path.join(ROOT, "src", "capabilities", "cli-flags.generated.ts");
const COMMANDS = [
  "root",
  "compile",
  "watch",
  "query",
  "eval",
  "fonts",
  "init",
  "info",
  "completions",
];

function parseArgs(argv) {
  const options = { check: false, snapshotRoot: null };
  for (let index = 0; index < argv.length; index += 1) {
    const token = argv[index];
    if (token === "--check") options.check = true;
    else if (token === "--snapshot-root") options.snapshotRoot = argv[++index];
    else if (token.startsWith("--snapshot-root="))
      options.snapshotRoot = token.slice("--snapshot-root=".length);
    else throw new Error(`Unknown argument: ${token}`);
  }
  return options;
}

/** Turn per-release presence into `since`, `undocumentedFrom` and gaps. */
function lifetime(versions, present) {
  const first = versions.findIndex((version) => present.has(version));
  let last = -1;
  for (let index = versions.length - 1; index >= 0; index -= 1)
    if (present.has(versions[index])) {
      last = index;
      break;
    }
  const result = { since: versions[first] };
  if (last < versions.length - 1) result.undocumentedFrom = versions[last + 1];
  const absentIn = versions
    .slice(first, last + 1)
    .filter((version) => !present.has(version));
  if (absentIn.length > 0) result.absentIn = absentIn;
  return result;
}

async function collect(snapshotRoot) {
  const inventory = JSON.parse(
    await fs.readFile(path.join(ROOT, "data", "typst-releases.json"), "utf8"),
  );
  const versions = inventory.releases
    .map((release) => release.version)
    .sort(compareVersions);
  const presence = {};
  const valueKinds = {};
  for (const version of versions) {
    for (const command of COMMANDS) {
      const file = path.join(snapshotRoot, version, `${command}-help.json`);
      let snapshot;
      try {
        snapshot = JSON.parse(await fs.readFile(file, "utf8"));
      } catch {
        continue;
      }
      // A subcommand that does not exist prints an error instead of help.
      if (snapshot.exitCode !== 0) continue;
      const flags = parseHelpFlags(snapshot.stdout ?? "");
      for (const [name, info] of flags) {
        presence[command] ??= {};
        presence[command][name] ??= { versions: new Set(), values: {} };
        const entry = presence[command][name];
        entry.versions.add(version);
        valueKinds[`${command} ${name}`] = info.value;
        for (const value of info.values) {
          entry.values[value] ??= new Set();
          entry.values[value].add(version);
        }
      }
    }
  }
  const commands = {};
  for (const command of COMMANDS) {
    if (presence[command] === undefined) continue;
    commands[command] = {};
    for (const name of Object.keys(presence[command]).sort()) {
      const entry = presence[command][name];
      const record = {
        ...lifetime(versions, entry.versions),
        value: valueKinds[`${command} ${name}`],
      };
      const values = Object.keys(entry.values).sort();
      if (values.length > 0) {
        record.values = Object.fromEntries(
          values.map((value) => [
            value,
            lifetime(versions, entry.values[value]),
          ]),
        );
      }
      commands[command][name] = record;
    }
  }
  return { versions, commands };
}

function render(data) {
  return `// Generated by scripts/generate-cli-flags.mjs from the exact per-release
// --help snapshots in flukxr/typst-snapshots. Do not edit by hand.
//
// For each subcommand ("root" holds the global options) and each long flag:
// the first exact release that documents it (\`since\`), the first release
// whose help no longer lists it (\`undocumentedFrom\`), releases in between
// that lack it (\`absentIn\`), whether it takes a value, and the same lifetime
// for every documented value.
//
// A flag missing from the help is not necessarily removed: Typst hides
// deprecated flags that still work (\`--make-deps\` from 0.14.0). Removal is
// decided from the real binary and recorded in the capability registry.

export interface CliFlagLifetime {
  readonly since: string;
  readonly undocumentedFrom?: string;
  readonly absentIn?: readonly string[];
}

export interface CliFlagRecord extends CliFlagLifetime {
  readonly value: "none" | "required" | "optional";
  readonly values?: Readonly<Record<string, CliFlagLifetime>>;
}

export const CLI_FLAG_VERSIONS: readonly string[] = ${JSON.stringify(data.versions)};

export const CLI_FLAGS: Readonly<
  Record<string, Readonly<Record<string, CliFlagRecord>>>
> = ${JSON.stringify(data.commands, null, 2)};
`;
}

const options = parseArgs(process.argv.slice(2));
const snapshotRoot = path.resolve(
  options.snapshotRoot ?? repositorySnapshotRoot(),
);
let hasCorpus = true;
try {
  await fs.access(path.join(snapshotRoot, "0.1.0", "root-help.json"));
} catch {
  hasCorpus = false;
}
if (!hasCorpus) {
  const message = `No snapshot corpus at ${snapshotRoot}; CLI flag inventory not ${options.check ? "checked" : "regenerated"}.`;
  if (options.check) {
    console.log(message);
    process.exit(0);
  }
  throw new Error(message);
}

const generated = await prettier.format(render(await collect(snapshotRoot)), {
  ...((await prettier.resolveConfig(OUTPUT)) ?? {}),
  filepath: OUTPUT,
});
if (options.check) {
  let committed = "";
  try {
    committed = await fs.readFile(OUTPUT, "utf8");
  } catch {}
  const normalise = (text) => text.replace(/\r\n/gu, "\n").trim();
  if (normalise(committed) !== normalise(generated)) {
    console.error(
      "src/capabilities/cli-flags.generated.ts is out of date; run node scripts/generate-cli-flags.mjs.",
    );
    process.exit(1);
  }
  console.log("CLI flag inventory is current.");
} else {
  await fs.writeFile(OUTPUT, generated, "utf8");
  console.log(`Wrote ${path.relative(ROOT, OUTPUT)}.`);
}
